"""Create a bounded ZIP of private client profiles and their import QR codes."""

import base64
import io
import json
import re
import struct
import zipfile
import zlib
from dataclasses import dataclass, field

import segno
from PIL import Image

_MAX_ZIP = 48 * 1024 * 1024
_MAX_PROFILE = 128 * 1024
_MAX_AMNEZIA_FRAMES = 12
_AMNEZIA_CHUNK = 850


class ArchiveTooLarge(Exception):
    pass


@dataclass
class Profile:
    name: str
    files: dict[str, str] = field(default_factory=dict)
    qr: dict[str, tuple[str, bool]] = field(default_factory=dict)
    warnings: list[str] = field(default_factory=list)


def amnezia_payload(link: str) -> bytes:
    encoded = link.removeprefix("vpn://")
    return base64.b64decode(encoded + "=" * (-len(encoded) % 4), altchars=b"-_", validate=True)


def xray_native_config(link: str) -> str:
    """Read the native JSON from a link generated by app.xray."""
    source = json.loads(zlib.decompress(amnezia_payload(link)[4:]))
    native = json.loads(source["containers"][0]["xray"]["last_config"])
    return json.dumps(native, ensure_ascii=False, indent=2) + "\n"


def amnezia_frames(link: str) -> list[bytes]:
    data = amnezia_payload(link)
    if not data:
        raise ValueError("empty profile")
    chunks = [data[offset:offset + _AMNEZIA_CHUNK]
              for offset in range(0, len(data), _AMNEZIA_CHUNK)]
    if len(chunks) > _MAX_AMNEZIA_FRAMES:
        raise ValueError("too many frames")
    return [
        base64.urlsafe_b64encode(struct.pack(">HBBI", 1984, len(chunks), number, len(chunk)) + chunk).rstrip(b"=")
        for number, chunk in enumerate(chunks)
    ]


def _qr_png(data: str | bytes) -> bytes:
    result = io.BytesIO()
    segno.make(data, error="L", micro=False, boost_error=False,
               mode="byte", encoding="utf-8").save(result, kind="png", scale=3)
    return result.getvalue()


def _qr_gif(png_frames: list[bytes]) -> bytes:
    frames = []
    for png in png_frames:
        with Image.open(io.BytesIO(png)) as image:
            frames.append(image.convert("L"))

    # Keep QR modules at their original size and the quiet zone white.
    # The final chunk can produce a smaller QR than the preceding chunks.
    size = max(frame.width for frame in frames)
    canvases = []
    for frame in frames:
        offset = (size - frame.width) // 2
        canvas = Image.new("L", (size, size), 255)
        canvas.paste(frame, (offset, offset))
        canvases.append(canvas)

    result = io.BytesIO()
    canvases[0].save(result, format="GIF", save_all=True, append_images=canvases[1:],
                     duration=500, loop=0, optimize=False)
    return result.getvalue()


def build(protocol: str, ids: list[str], profiles: dict[str, Profile]) -> tuple[bytes, int]:
    output = io.BytesIO()
    manifest = {"protocol": protocol, "items": []}
    exported = 0
    with zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as archive:
        for number, cid in enumerate(ids, 1):
            if (profile := profiles.get(cid)) is None:
                manifest["items"].append({"client_id": cid, "status": "profile_missing"})
                continue
            name = re.sub(r"[^A-Za-z0-9_-]+", "_", profile.name).strip("_")[:56] or "client"
            folder = f"{number:04}-{name}"
            paths = []
            warnings = profile.warnings.copy()
            for filename, content in profile.files.items():
                if not content or len(content.encode("utf-8")) > _MAX_PROFILE:
                    warnings.append(f"{filename}: profile_too_large_or_empty")
                    continue
                path = f"{folder}/{filename}"
                archive.writestr(path, content)
                paths.append(path)
            if paths:
                exported += 1
                for label, (content, amnezia) in profile.qr.items():
                    if not content or len(content.encode("utf-8")) > _MAX_PROFILE:
                        warnings.append(f"{label}: qr_unavailable")
                        continue
                    try:
                        frames = amnezia_frames(content) if amnezia else [content]
                        rendered = [_qr_png(frame) for frame in frames]
                    except ValueError:
                        warnings.append(f"{label}: qr_unavailable")
                        continue
                    for index, png in enumerate(rendered, 1):
                        suffix = f"-{index:02}" if len(rendered) > 1 else ""
                        path = f"{folder}/{label}{suffix}.png"
                        archive.writestr(path, png)
                        paths.append(path)
                    if len(rendered) > 1:
                        path = f"{folder}/{label}.gif"
                        archive.writestr(path, _qr_gif(rendered))
                        paths.append(path)
            manifest["items"].append({
                "client_id": cid, "name": profile.name, "status": "exported" if paths else "profile_invalid",
                "files": paths, "warnings": warnings,
            })
            if output.tell() > _MAX_ZIP:
                raise ArchiveTooLarge
        archive.writestr("manifest.json", json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    if output.tell() > _MAX_ZIP:
        raise ArchiveTooLarge
    return output.getvalue(), exported
