/**
 * Склейка коротких пропусков в ряду для стека.
 *
 * В стеке пропуск одного ряда роняет все ряды над ним: пропущенный сбор у
 * крупного сервера прорезал график сверху донизу и выглядел как авария, хотя
 * это пара пустых точек. Короткую дыру внутри ряда (данные есть с обеих сторон)
 * закрываем последним значением, как "connect null values" в Grafana. Длинная
 * дыра - сервер правда лежал - остается провалом.
 */
export function bridgeGaps(
  values: (number | null)[],
  maxGap = 3,
): (number | null)[] {
  const out = [...values]
  let i = 0
  while (i < out.length) {
    if (out[i] != null) {
      i++
      continue
    }
    let j = i
    while (j < out.length && out[j] == null) j++
    const inside = i > 0 && j < out.length
    if (inside && j - i <= maxGap) {
      for (let k = i; k < j; k++) out[k] = out[i - 1]
    }
    i = j
  }
  return out
}

/**
 * Прирост счетчика за точку. Счетчик сбросился (рестарт, перевыпуск) - прирост
 * считаем нулем, а не отрицательным.
 */
export function deltasFromTotals(totals: number[]): number[] {
  return totals.map((v, i) => (i === 0 ? 0 : Math.max(0, v - totals[i - 1])))
}

/**
 * Скорость: прирост за точку, деленный на время от предыдущей точки.
 *
 * Именно скорость, а не "байт за точку": шаг точки зависит от ширины окна
 * (5 минут на сутках, 12 часов на 90 днях), и байты за точку на разных окнах
 * несравнимы. Делим на реальный промежуток, а не на номинальный интервал:
 * пропущенный сбор копит прирост за двойное время, и скорость вышла бы вдвое
 * выше настоящей. У первой точки сравнивать не с чем - null, иначе график
 * начинался бы провалом в ноль.
 */
export function toRate(deltas: number[], ts: number[]): (number | null)[] {
  return deltas.map((d, i) =>
    i === 0 ? null : d / Math.max(1, (ts[i] - ts[i - 1]) / 1000),
  )
}

// единица в тон остальной панели: там объемы везде в B / KiB / MiB / GiB
export function formatRate(bytesPerSec: number): string {
  return `${formatBytes(bytesPerSec)}/s`
}
